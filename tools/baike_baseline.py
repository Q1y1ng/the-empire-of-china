# -*- coding: utf-8 -*-
"""从《帝国高层人物小传(2026)》抽取 57 人速查表，生成 docs/baike/口径基线.md。

用途：百科词条扩写时的唯一人事口径来源。凡词条内出现姓名、生年、品级、
现职、籍贯，一律以此表为准。

用法：py -3 tools/baike_baseline.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "设定" / "帝国高层人物小传(2026).md"
OUT = ROOT / "docs" / "baike" / "口径基线.md"

ROW = re.compile(
    r"(?m)^\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|"
)


def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    rows = []
    for m in ROW.finditer(text):
        idx, name, post, rank, birth, native = (g.strip() for g in m.groups())
        if name in ("姓名",):  # 表头
            continue
        rows.append((int(idx), name, post, rank, birth, native))
    rows.sort()
    if len(rows) != 57:
        print(f"[warn] 期望 57 行，实得 {len(rows)} 行", file=sys.stderr)

    lines = [
        "# 百科口径基线（2026）",
        "",
        "> 本文件由 `tools/baike_baseline.py` 从《帝国高层人物小传（2026）》自动生成，**请勿手改**。",
        "> 百科词条扩写时，凡涉及下列 57 人的姓名、生年、品级、现职、籍贯，一律以本表为准；",
        "> 表中未列者，以《全国官员名录》对应卷为准；名录亦无者，不得自造。",
        "",
        "## 一、57 人基础表",
        "",
        "| 序 | 姓名 | 现职 | 品级 | 生年 | 籍贯 |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        lines.append("| {} | {} | {} | {} | {} | {} |".format(*r))

    lines += [
        "",
        "## 二、词组口径（同义词只许一写法）",
        "",
        "| 概念 | 唯一写法 | 禁用写法 |",
        "| --- | --- | --- |",
        "| 政治局 | 中央政治局 | 政治局（单用） |",
        "| 常委会 | 中央政治局常务委员会 | 政治局常委会（单用） |",
        "| 政委会 | 中央政治委员会 | 政治委员会（单用） |",
        "| 政代会 | 全国政治代表会议／州政治代表会议 | 政治代表会 |",
        "| 议会 | 国民议会 | 议会（单用，指地方时须写州议政会） |",
        "| 纪委 | 中央纪律检查委员会 | 中纪委 |",
        "| 监委 | 国家监察委员会 | 监察委 |",
        "| 品级 | 一品正国、二品副国、三品州部、四品厅局……十品副处 | 部级、副部级（除非明写对应品级） |",
        "",
        "## 三、2026 年必守数据（引自《帝国主数据表（2026）》）",
        "",
        "| 项 | 值 |",
        "| --- | --- |",
        "| GDP | 360.0 万亿元人民币／60.0 万亿美元；全球占比 40.0% |",
        "| 世界 GDP 总量 | 150.0 万亿美元 |",
        "| 人均 GDP | 202,200 元／33,700 美元 |",
        "| 财政收入 | 100.80 万亿元（占 GDP 28.0%） |",
        "| 财政支出 | 110.88 万亿元（占 GDP 30.8%） |",
        "| 赤字 | 10.08 万亿元（占 GDP 2.8%） |",
        "| 税收／非税 | 87.00 万亿元／13.80 万亿元 |",
        "| 国防 | 14.41 万亿元（占 GDP 4.0%） |",
        "| 教育 | 7.21 万亿元 |",
        "| 社会保障 | 24.39 万亿元 |",
        "| 卫生 | 9.98 万亿元 |",
        "| 科技 | 5.99 万亿元 |",
        "| 基础设施 | 12.20 万亿元 |",
        "| 全民基本补贴 | 1,030 元／月／人；年度 22.00 万亿元 |",
        "| 自动化红利基金 | 年度可分配 8.01 万亿元 |",
        "| 平均工资 | 16,420 元／月（年薪 197,040 元） |",
        "| 三次产业 | 4.2%／38.6%／57.2%（15.12／138.96／205.92 万亿元） |",
        "| 制造业 | 18.0 万亿美元（全球 36%） |",
        "| 对外贸易 | 12.0 万亿美元（全球 26%） |",
        "| 对外净资产 | 8.0 万亿美元 |",
        "| 中华元储备占比 | 32% |",
        "| 研发投入 | 12.96 万亿元（占 GDP 3.6%，全球 40%） |",
        "| 高铁／铁路／城轨 | 9.2 万公里／24.0 万公里／18,600 公里 |",
        "| 人均预期寿命 | 82.8 岁 |",
        "| 高等教育毛入学率 | 76% |",
        "| 中央政治委员会 | 80 人（含主席皇帝 1 席，委员 79）：一品 9、二品 42、三品 29 |",
        "| 中央政治局 | 27 人 |",
        "| 中央政治局常务委员会 | 9 人 |",
        "| 国民议会 | 720 席 |",
        "| 省／州 | 39 个省级单位；7 州＋京畿直隶州 |",
        "",
        "## 四、禁止出现的表述",
        "",
        "- 「史实原型」「†」「（史实原型生年）」等溯源标注；",
        "- 「新民主主义」「社会主义」「共产党」「马克思」等现实政治名词；",
        "- 「筹建中」「拟设」「计划成立」等未定状态（除《帝国编年史》明确记载者）；",
        "- 以否定句式作主干定义（「X 不是 Y」「X 并非 Z」，见《百科编撰规范》§三）。",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"已生成 {OUT.relative_to(ROOT)}：{len(rows)} 人")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
