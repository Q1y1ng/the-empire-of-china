# ---------------------------------------------------------------- 自检
def check():
    """校验分区面积与设定值偏差，返回 [(名, 实际 ha, 设定 ha, 偏差%)]。"""
    out = []
    for z in ZONES:
        if z["key"] == "service":
            continue
        actual = (z["x1"] - z["x0"]) * (z["y1"] - z["y0"]) / 1e4
        dev = (actual - z["ha"]) / z["ha"] * 100
        out.append((z["name"], round(actual, 2), z["ha"], round(dev, 1)))
    total = sum(o[1] for o in out)
    out.append(("分区块合计（余量为门庭巷道值房）", round(total, 2),
                round(sum(z["ha"] for z in ZONES if z["key"] != "service"), 2), 0.0))
    out.append(("宫城总面积", round(PALACE["width"] * PALACE["depth"] / 1e4, 2),
                PALACE["area_ha"], 0.0))
    return out


