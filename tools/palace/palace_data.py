def service_blocks():
    """值房/库房：沿城墙内侧一圈的示意排布（【推定】）。返回 [(cx, cy, w, d, h)]。"""
    blocks = []
    inner = PALACE["width"] / 2 - PALACE["wall_t"] / 2 - 12   # 距墙内皮的块中心
    depp = PALACE["depth"] / 2 - PALACE["wall_t"] / 2 - 12
    for x in (-inner, inner):
        y = -430.0
        while y <= 430.0:
            if not (-350 <= y <= -20):            # 东西厢（紫光阁群 / 政枢殿群）让出
                blocks.append((x, y, 12.0, 40.0, 5.0))
            y += 58.0
    for y in (-depp, depp):
        x = -330.0
        while x <= 330.0:
            if abs(x) > 70:                       # 让开中轴门楼
                if y > 0 and abs(x) < 240:        # 北墙中段被琼苑占用
                    x += 58.0
                    continue
                blocks.append((x, y, 40.0, 12.0, 5.0))
            x += 58.0
    return blocks


