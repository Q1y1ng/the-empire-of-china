def main():
    apply = '--apply' in sys.argv
    cache = {}
    rows = []
    bad = 0
    for i, e in enumerate(EDITS, 1):
        p = e['f']
        if p not in cache:
            with io.open(p, 'r', encoding='utf-8', newline='') as fh:
                cache[p] = fh.read()
        text = cache[p]
        c = text.count(e['old'])
        ok = (c == e['n'])
        if not ok:
            bad += 1
        rows.append((i, os.path.basename(p), e['n'], c, ok))
        if ok and apply:
            cache[p] = text.replace(e['old'], e['new'], e['n'])

    for i, name, exp, got, ok in rows:
        flag = 'OK  ' if ok else 'MISS'
        print('%s #%02d %-42s expect=%d got=%d' % (flag, i, name, exp, got))

    print('\n合计 %d 条，命中异常 %d 条' % (len(EDITS), bad))
    if bad:
        print('有 MISS，未落盘。')
        return 1
    if not apply:
        print('干跑通过（未落盘）。加 --apply 执行。')
        return 0

    for p, text in cache.items():
        with io.open(p, 'w', encoding='utf-8', newline='') as fh:
            fh.write(text)
    print('已写入 %d 个文件。' % len(cache))
    return 0


if __name__ == '__main__':
    sys.exit(main())
