# -*- coding: utf-8 -*-
"""议会九专委表：删「副主任」列（四品副职不再具名）。"""
import io, re

ROWS = {
 '财政经济委员会': '财政部、国家发展改革委员会、帝国中央银行、审计院',
 '宪法与法律委员会': '宪法法院、司法部',
 '监察与司法委员会': '中央纪委、国家监委、两高',
 '科技教育文化委员会': '教育部、科学技术部、文化和旅游部',
 '社会民生委员会': '人社部、卫健委、住建部',
 '外事委员会': '外交部',
 '国防与安全委员会': '国防部、中央军委、国安委',
 '民族事务委员会': '国家民族事务委员会',
 '资源环境与基建委员会': '自然资源部、生态环境部、交通运输部',
}
DIRS = ['潘立言', '狄宪文', '屈静仪', '沙孟章', '贺慕贞', '巩叙远', '阙定边', '石承宗', '裴启元']

for p in ['设定/国民议会(2026).md', '中华帝国设定全书(2026).md']:
    t = io.open(p, encoding='utf-8').read()
    n = 0
    for (name, dept), d in zip(ROWS.items(), DIRS):
        pat = re.compile(r'^\| ' + name + r' \| ' + d + r' \| [^|]+ \| ([^|]+) \|$', re.M)
        if pat.search(t):
            t = pat.sub(f'| {name} | {d} | {dept} |', t, count=1)
            n += 1
    t = t.replace('| 专门委员会 | 主任 | 副主任 | 对口部门 |', '| 专门委员会 | 主任 | 对口部门 |')
    t = t.replace('| --- | --- | --- | --- |\n| 财政经济委员会', '| --- | --- | --- |\n| 财政经济委员会')
    io.open(p, 'w', encoding='utf-8').write(t)
    print(p, '改写行', n)
